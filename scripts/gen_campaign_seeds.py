def generate(path: str) -> int:
    """Write the seed JSONL; returns the number of seeds."""
    count = 0
    with open(path, "w", encoding="utf-8") as fh:
        for category, urls in SEEDS.items():
            seen_hosts: set[str] = set()
            for url in urls:
                host = url.split("/")[2] if "://" in url else url
                variants = [url]
                # one deep-page variant per host for a third of the corpus
                if host not in seen_hosts and count % 3 == 0:
                    variants.append(url.rstrip("/") + "/about")
                seen_hosts.add(host)
                for variant in variants:
                    fh.write(
                        json.dumps({"url": variant, "category": category}, ensure_ascii=False)
                        + "\n"
                    )
                    count += 1
    return count


